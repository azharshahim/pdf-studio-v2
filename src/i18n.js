let currentLang = 'fr';

export function getLang() {
  return currentLang;
}

export function t(key) {
  return DICT[currentLang]?.[key] ?? DICT.fr[key] ?? key;
}

/** Applique une langue : textes, placeholders, direction RTL et <html lang>. */
export function applyLanguage(lang) {
  currentLang = LANGS[lang] ? lang : 'fr';
  const meta = LANGS[currentLang];
  document.documentElement.lang = currentLang;
  document.documentElement.dir = meta.dir;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    const value = t(key);
    if (!value) return;
    if (el.hasAttribute('data-i18n-html')) el.innerHTML = value;
    else el.textContent = value;
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const value = t(el.dataset.i18nPlaceholder);
    if (value) el.placeholder = value;
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const value = t(el.dataset.i18nTitle);
    if (value) {
      el.title = value;
      el.setAttribute('aria-label', value);
    }
  });
}
